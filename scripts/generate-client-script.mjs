#!/usr/bin/env node
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
import { build } from "esbuild";

const checkOnly = process.argv.includes("--check");
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = resolve(root, "packages/helper/src/cli.ts");
const bundlePath = resolve(root, "packages/helper/client/j01n.js");
const targetPath = resolve(root, "packages/helper/src/client-script.ts");
const result = await build({ entryPoints: [sourcePath], bundle: true, platform: "node", target: "node20", format: "esm", write: false, legalComments: "none" });
const script = result.outputFiles[0].text.replace(/^#![^\n]*\n/, `#!/usr/bin/env node\n/* j01n.me standalone encrypted client. No npm deps.\n   Quick start: curl -fsSL https://j01n.me/client/j01n.js -o .j01n/j01n.js\n   Commands: create, join, send, read, inbox, watch, wait, doctor, webhook, kickoff, profile, host, reserve, release, reservations, leave, register, allow, invite, invites, listen, team\n*/\n`);
const output = `/**
 * The standalone j01n.me CLI, served at /client/j01n.js.
 * Generated from packages/helper/src/cli.ts and @j01n/sdk by scripts/generate-client-script.mjs.
 * Do not edit this file directly.
 */
export const clientScript: string = ${JSON.stringify(script)};
`;
if (checkOnly) {
  const [bundle, current] = await Promise.all([readFile(bundlePath, "utf8").catch(() => ""), readFile(targetPath, "utf8").catch(() => "")]);
  if (bundle !== script || current !== output) {
    console.error("helper client bundle or embedded script is out of date. Run pnpm generate:client-script.");
    process.exit(1);
  }
  console.log("helper client bundle and embedded script are up to date");
} else {
  await Promise.all([writeFile(bundlePath, script), writeFile(targetPath, output)]);
  console.log(`generated ${bundlePath} and ${targetPath}`);
}
